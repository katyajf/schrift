import type { Article } from "@/lib/database.types";

// de is always blue and het always terracotta, everywhere in the app, so the
// article becomes something you recognise by sight.
export function ArticleTag({ article, className = "" }: { article: Article | null; className?: string }) {
  if (!article) return null;
  return <span className={`font-dutch ${article === "de" ? "text-de" : "text-het"} ${className}`}>{article}</span>;
}

export function DutchTerm({
  dutch,
  article,
  className = "",
}: {
  dutch: string;
  article: Article | null;
  className?: string;
}) {
  return (
    <span className={`font-dutch ${className}`}>
      {article && (
        <>
          <ArticleTag article={article} className="text-[0.7em]" />{" "}
        </>
      )}
      {dutch}
    </span>
  );
}

export function AiBadge({ className = "" }: { className?: string }) {
  return (
    <span
      title="Generated by AI"
      className={`inline-flex items-center rounded border border-line-strong px-1 text-[10px] leading-4 font-medium tracking-wide text-muted ${className}`}
    >
      AI
    </span>
  );
}
